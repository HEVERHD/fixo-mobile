import { useEffect, useState } from 'react'
import { View, Text, TouchableOpacity, Alert } from 'react-native'
import { KeyboardAwareScrollView } from 'react-native-keyboard-controller'
import { useSafeAreaInsets } from 'react-native-safe-area-context'
import { StatusBar } from 'expo-status-bar'
import { router } from 'expo-router'
import { X, Building2, Package, Tag, Hash, MapPin, QrCode } from 'lucide-react-native'
import { supabase } from '@/lib/supabase'
import { TextField } from '@/components/TextField'
import { SelectField, type SelectOption } from '@/components/SelectField'
import { ChipGroup } from '@/components/ChipGroup'
import { PrimaryButton } from '@/components/AuthLayout'
import { AppModal } from '@/components/AppModal'

const ASSET_TYPES = ['Climatización', 'Eléctrico', 'Hidráulico', 'Generación eléctrica', 'Refrigeración', 'Otro'] as const
type AssetType = typeof ASSET_TYPES[number]

type AssetStatus = 'activo' | 'en_mantenimiento' | 'fuera_de_servicio'

export default function NuevoEquipo() {
  const insets = useSafeAreaInsets()

  const [clients, setClients] = useState<SelectOption[]>([])
  const [clientId, setClientId] = useState<string | null>(null)
  const [name, setName] = useState('')
  const [type, setType] = useState<AssetType>('Climatización')
  const [brand, setBrand] = useState('')
  const [model, setModel] = useState('')
  const [location, setLocation] = useState('')
  const [status, setStatus] = useState<AssetStatus>('activo')

  const [errors, setErrors] = useState<{ client?: string; name?: string }>({})
  const [saving, setSaving] = useState(false)
  const [created, setCreated] = useState<{ name: string; qr: string } | null>(null)

  useEffect(() => {
    supabase.from('clients').select('id, company_name, address').order('company_name')
      .then(({ data }) => setClients((data ?? []).map(c => ({ id: c.id, label: c.company_name, sublabel: c.address }))))
  }, [])

  async function save() {
    const next: typeof errors = {}
    if (!clientId) next.client = 'Elige el cliente dueño del equipo'
    if (name.trim().length < 3) next.name = 'Escribe un nombre que lo identifique'
    setErrors(next)
    if (Object.keys(next).length) return

    setSaving(true)
    // qr_code is generated by the database default
    const { data, error } = await supabase
      .from('assets')
      .insert({
        client_id: clientId,
        name: name.trim(),
        type,
        brand: brand.trim() || null,
        model: model.trim() || null,
        location: location.trim() || null,
        status,
      })
      .select('qr_code')
      .single()
    setSaving(false)

    if (error || !data) {
      Alert.alert('No se pudo crear el equipo', 'Revisa tu conexión e inténtalo de nuevo.')
      return
    }
    setCreated({ name: name.trim(), qr: data.qr_code })
  }

  return (
    <View className="flex-1 bg-gray-50">
      <StatusBar style="dark" />

      <View className="flex-row items-center px-4 pb-3 bg-white border-b border-gray-100" style={{ paddingTop: insets.top + 8 }}>
        <TouchableOpacity onPress={() => router.back()} hitSlop={10} accessibilityRole="button" accessibilityLabel="Cancelar">
          <X size={24} color="#374151" />
        </TouchableOpacity>
        <Text className="text-lg font-bold text-gray-900 ml-4">Nuevo equipo</Text>
      </View>

      <KeyboardAwareScrollView
        bottomOffset={96}
        keyboardShouldPersistTaps="handled"
        contentContainerStyle={{ padding: 16, paddingBottom: insets.bottom + 24, gap: 20 }}
      >
        <SelectField
          label="Cliente"
          icon={Building2}
          placeholder="¿De quién es el equipo?"
          options={clients}
          value={clientId}
          onChange={id => { setClientId(id); setErrors(e => ({ ...e, client: undefined })) }}
          error={errors.client}
          emptyText="Aún no tienes clientes registrados"
        />

        <TextField
          label="Nombre del equipo"
          icon={Package}
          placeholder="Ej. Aire acondicionado sala de juntas"
          value={name}
          onChangeText={t => { setName(t); if (errors.name) setErrors(e => ({ ...e, name: undefined })) }}
          error={errors.name}
        />

        <ChipGroup label="Tipo" value={type} onChange={setType} options={ASSET_TYPES.map(t => ({ value: t, label: t }))} />

        <TextField label="Marca (opcional)" icon={Tag} placeholder="Ej. Carrier" value={brand} onChangeText={setBrand} />

        <TextField
          label="Modelo o serial (opcional)"
          icon={Hash}
          placeholder="Ej. 42QHC"
          autoCapitalize="characters"
          autoCorrect={false}
          value={model}
          onChangeText={setModel}
        />

        <TextField
          label="Ubicación (opcional)"
          icon={MapPin}
          placeholder="Ej. Piso 2 - Quirófano 2"
          value={location}
          onChangeText={setLocation}
        />

        <ChipGroup
          label="Estado"
          value={status}
          onChange={setStatus}
          options={[
            { value: 'activo', label: 'Activo' },
            { value: 'en_mantenimiento', label: 'En mantenimiento' },
            { value: 'fuera_de_servicio', label: 'Fuera de servicio' },
          ]}
        />

        <PrimaryButton label="Crear equipo" onPress={save} loading={saving} className="mt-2" />
      </KeyboardAwareScrollView>

      <AppModal
        visible={created !== null}
        variant="success"
        icon={QrCode}
        title="¡Equipo creado!"
        actionLabel="Listo"
        onAction={() => { setCreated(null); router.back() }}
      >
        <Text className="text-base text-gray-600 text-center">
          <Text className="font-semibold text-gray-900">{created?.name}</Text> quedó registrado con el código
        </Text>
        <Text className="text-xl font-bold text-gray-900 text-center mt-2 tracking-widest">{created?.qr}</Text>
        <Text className="text-sm text-gray-500 text-center mt-2">
          Pronto podrás imprimir su QR para pegarlo en el equipo.
        </Text>
      </AppModal>
    </View>
  )
}
